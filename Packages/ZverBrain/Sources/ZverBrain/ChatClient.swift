import Foundation

/// Контракт одного обращения к чат-модели: system + user → текст ответа.
///
/// Намеренно минимален (одна операция, без стриминга и истории) — «мозгу» нужен
/// ровно один синхронный по смыслу запрос «сгенерируй ленту». За протоколом
/// прячется рантайм-`URLSession` (``OpenAICompatibleClient``), чтобы оркестрацию
/// (снапшот → промпт → парсинг) можно было тестировать против контракта.
public protocol ChatClient: Sendable {
    /// Выполняет один chat-запрос и возвращает текст ответа модели.
    /// - Throws: ``BrainError`` — типизированный сбой (auth/лимит/сеть/ответ).
    func complete(system: String, user: String) async throws -> String
}

/// Словарь ошибок «мозга» — типизирован и `Equatable`, чтобы тесты и UI
/// различали причины без разбора строк.
///
/// Ретраев тут нет (запуск ручной): любая ошибка возвращается как есть, решение
/// «повторить» принимает пользователь.
public enum BrainError: Error, Equatable, Sendable {
    /// Ключ битый/просрочен (HTTP 401/403). Нужен новый ключ.
    case unauthorized
    /// Превышен лимит запросов (HTTP 429). Стоит подождать и повторить вручную.
    case rateLimited
    /// Ответ не распознан: не-2xx статус, битый JSON, пустой `choices`.
    /// В строке — короткий обрезанный фрагмент тела/причины для диагностики.
    case badResponse(String)
    /// Транспортный сбой (нет сети, таймаут, обрыв). В строке — описание.
    case network(String)
    /// Ключ не задан (`BrainTokenProviding.token()` вернул `nil`/пусто) —
    /// в сеть не ходим.
    case missingToken
}
