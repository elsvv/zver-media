import Foundation

/// Пул категорий внешних рекомендаций «Главной» (дизайн «Предложка v2»).
///
/// Слаг (rawValue) — стабильный идентификатор: ходит в промпт, эхом
/// возвращается моделью в `HomeSection.category`, пишется в память показанного
/// и в настройку ротации. Менять слаги нельзя — сломается кэш и ротация.
///
/// ВЫБОР категорий на конкретный refresh делает приложение (ротация в
/// `HomeFeedService`) и передаёт список в ``HomeFeedPrompt/build(snapshot:categories:customInstructions:)``
/// параметром — сам промпт остаётся детерминированным.
public enum DiscoveryCategory: String, Codable, CaseIterable, Sendable {
    /// Якорь — «одержимость»: альбом с аномальной плотностью прослушиваний
    /// за последние 14 дней (блок ОДЕРЖИМОСТИ в снапшоте).
    case similarToObsession = "similar-to-obsession"
    /// Артисты ИЗ библиотеки, альбомы которых в ней отсутствуют —
    /// почти нулевые галлюцинации.
    case deeperDiscography = "deeper-discography"
    /// Канон в жанрах слушателя, отсутствующий в библиотеке.
    case missedClassics = "missed-classics"
    /// Нишевое с анти-канон инструкцией; валидацией отсеивается чаще — на то и запас.
    case digDeeper = "dig-deeper"
    /// Только при `webSearch == true` активного профиля: релизы последних недель из веба.
    case freshReleases = "fresh-releases"
    /// Шаг вбок через общую нить (продюсер, лейбл, эпоха) с объяснением моста.
    case sideways = "sideways"
    /// Погружение в сцену или лейбл («весь ранний Warp», кентерберийская сцена).
    case sceneDive = "scene-dive"
    /// Те же вкусовые векторы, но из декады, где слушатель не копался.
    case timeTravel = "time-travel"

    /// Человекочитаемое название — для UI и как заголовок-подсказка модели.
    public var title: String {
        switch self {
        case .similarToObsession: "Похоже на твоё последнее"
        case .deeperDiscography: "Глубже в дискографию"
        case .missedClassics: "Классика, которую ты пропустил"
        case .digDeeper: "Копни глубже"
        case .freshReleases: "Свежие релизы для тебя"
        case .sideways: "Совсем другое"
        case .sceneDive: "Сцена / лейбл"
        case .timeTravel: "Из другого времени"
        }
    }

    /// Инструкция для промпта: какую механику подбора применить в секции.
    public var promptInstruction: String {
        switch self {
        case .similarToObsession:
            "Оттолкнись от блока ОДЕРЖИМОСТИ — это последнее сильное увлечение слушателя. " +
            "Предложи альбомы, максимально близкие по духу и звуку к этим одержимостям."
        case .deeperDiscography:
            "Возьми артистов ИЗ библиотеки слушателя и предложи их альбомы, которых " +
            "в библиотеке НЕТ. Никаких новых артистов — только углубление в знакомых."
        case .missedClassics:
            "Признанная классика в жанрах слушателя, которой нет в его библиотеке: " +
            "общепризнанные вершины, мимо которых он прошёл."
        case .digDeeper:
            "Нишевое и малоизвестное под вкус слушателя. АНТИ-КАНОН: ничего из " +
            "общеизвестных топов и хрестоматийных списков «лучших альбомов» — " +
            "только глубокие врезки, которые знают копатели."
        case .freshReleases:
            "Релизы ПОСЛЕДНИХ НЕДЕЛЬ: ищи их в вебе, а не в своей памяти — " +
            "твои знания устаревают, доверяй только результатам свежего поиска."
        case .sideways:
            "Шаг вбок: другое звучание, связанное с любимым общей нитью — продюсер, " +
            "лейбл, эпоха, сцена. В reason обязательно объясни этот мост."
        case .sceneDive:
            "Погружение в одну сцену или один лейбл, созвучные вкусу слушателя " +
            "(в духе «весь ранний Warp» или «кентерберийская сцена»)."
        case .timeTravel:
            "Те же вкусовые векторы, но из декады, в которой слушатель ещё не копался."
        }
    }
}
