import Foundation

/// Целевое качество PCM при конвертации DSD (`.dsf`) → FLAC на Маке.
///
/// DSD нельзя проиграть на iPhone bit-perfect (iOS не выводит DSD/DoP), поэтому
/// Мак декодирует его в высокое разрешение PCM и кодирует во FLAC. Выбор — между
/// «ближе к полосе DSD» и «вдвое компактнее, прозрачно для слуха». Разрядность
/// всегда 24 бита (с запасом над реальным динамическим диапазоном DSD).
enum DSDQuality: String, CaseIterable, Sendable, Identifiable {
    /// 176.4 кГц — децимация ÷16 от DSD64, максимум полосы. По умолчанию.
    case hi
    /// 88.2 кГц — децимация ÷32, вдвое компактнее, прозрачно для слуха.
    case standard

    var id: String { rawValue }

    /// Целевая частота дискретизации PCM в Гц (кратна 44.1к — как исходный DSD).
    var sampleRate: Int { self == .hi ? 176_400 : 88_200 }

    /// Разрядность итогового FLAC.
    var bitDepth: Int { 24 }

    /// Подпись для пикера в окне импорта.
    var label: String {
        self == .hi ? "176.4 кГц / 24-бит (макс.)" : "88.2 кГц / 24-бит (компактно)"
    }

    static var `default`: DSDQuality { .hi }
}
